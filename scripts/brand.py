def surfaces(b: Brand) -> list[tuple[Path, str]]:
    """Whole files this script owns."""
    return [
        (ROOT / "design-system" / "tokens.css", tokens_css(b)),
        (ROOT / "design-system" / "tokens.py", tokens_py(b)),
        (ROOT / "design-system" / "tokens.sh", tokens_sh(b)),
        (ROOT / "design-system" / "marked.mplstyle", mplstyle(b)),
        (ROOT / ".pi" / "extensions" / "confidentiality-broker" / "brand.generated.ts", brand_ts(b)),
        (ROOT / "site" / "favicon.svg", favicon(b)),
    ]


#: Every page we author carries its marking above its title. The repository is public,
#: so the line reads PUBLIC even where the page discusses a confidential workspace, as
#: design-system/guidelines/30-github-cover.md says. docs/challenge.md is the sponsor's
#: brief, quoted rather than written here, so it is left exactly as it arrived.
MARKED_PAGES = [
    (".github", "PULL_REQUEST_TEMPLATE.md"),
    (".pi", "extensions", "confidentiality-broker", "README.md"),
    ("demo", "README.md"),
    ("design-system", "README.md"),
    ("docs", "decisions.md"),
    ("docs", "cloud-setup.md"),
]


def blocks(b: Brand) -> list[tuple[Path, str, str, str]]:
    """Regions this script owns inside files a person writes."""
    return [
        (ROOT / "README.md", *block("marking", readme_marking(b))),
        *((ROOT.joinpath(*page), *block("marking", b.marking("public"))) for page in MARKED_PAGES),
        (ROOT / "site" / "index.html", *block("tokens", site_tokens(b), "css")),
        (ROOT / "site" / "index.html", *block("band-top", site_band(b))),
        (ROOT / "site" / "index.html", *block("band-bottom", site_band(b, bottom=True))),
        (ROOT / "design-system" / "README.md", *block("marking-table", ds_marking_table(b))),
        (ROOT / "demo" / "DEMO.md", *block("workspaces", demo_workspace_table(b))),
    ]


def run(check: bool) -> int:
    b = load()
    stale: list[str] = []
    wrote: list[str] = []

    for path, content in surfaces(b):
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            wrote.append(path.relative_to(ROOT).as_posix())

    unmarked: list[str] = []
    for path, open_, close, body in blocks(b):
        if not path.exists():
            stale.append(f"{path.relative_to(ROOT).as_posix()} (missing)")
            continue
        current = path.read_text(encoding="utf-8")
        try:
            updated = replace_block(current, open_, close, body)
        except RuntimeError:
            unmarked.append(f"{path.relative_to(ROOT).as_posix()} has no {open_} block yet")
            continue
        if updated == current:
            continue
        if check:
            stale.append(f"{path.relative_to(ROOT).as_posix()} [{open_}]")
        else:
            path.write_text(updated, encoding="utf-8")
            wrote.append(f"{path.relative_to(ROOT).as_posix()} [{open_}]")

    covers = [(ROOT / "docs" / "cover-light.svg", "light"), (ROOT / "docs" / "cover-dark.svg", "dark")]
    card = ROOT / "site" / "social-card.png"
    if inkscape() is None:
        print("brand: inkscape is not installed, so the covers and the social card were skipped", file=sys.stderr)
    elif check:
        # Regenerating an SVG is not byte stable across inkscape versions, so check the
        # facts the cover states rather than its bytes: the provider count in the ladder.
        for path, _ in covers:
            if not path.exists():
                stale.append(f"{path.relative_to(ROOT).as_posix()} (missing)")
                continue
            text = path.read_text(encoding="utf-8")
            expected = f"{len(b.cleared(b.levels[0]))} of {len(b.providers)}"
            if expected.replace(" ", "") not in re.sub(r"\s+", "", "".join(re.findall(r'aria-label="([^"]*)"', text))):
                stale.append(f"{path.relative_to(ROOT).as_posix()} (the clearance ladder does not match the policy)")
        if not card.exists():
            stale.append("site/social-card.png (missing)")
    else:
        for path, theme in covers:
            flatten(cover_svg(b, theme), path)
            wrote.append(path.relative_to(ROOT).as_posix())
        social_png(b, card)
        wrote.append(card.relative_to(ROOT).as_posix())

    for note in unmarked:
        print(f"brand: {note}", file=sys.stderr)

    if check:
        if stale:
            print("brand: out of date, run python3 scripts/brand.py", file=sys.stderr)
            for name in stale:
                print(f"  {name}", file=sys.stderr)
            return 1
        print("brand: every marked surface matches tokens.json and .pi/confidentiality.json")
        return 0

    for name in wrote:
        print(f"brand: wrote {name}")
    if not wrote:
        print("brand: nothing to do, every marked surface was already current")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated surface is out of date")
    parser.add_argument("--list", action="store_true", help="print what this script owns")
    args = parser.parse_args()

    if args.list:
        b = load()
        for path, _ in surfaces(b):
            print(path.relative_to(ROOT).as_posix())
        for path, open_, _, _ in blocks(b):
            print(f"{path.relative_to(ROOT).as_posix()} {open_}")
        print("docs/cover-light.svg\ndocs/cover-dark.svg\nsite/social-card.png")
        return 0
    return run(args.check)


if __name__ == "__main__":
    sys.exit(main())
