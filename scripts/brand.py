# --------------------------------------------------------------------------- model


class Brand:
    """The tokens and the policy, resolved."""

    def __init__(self, tokens: dict, policy: dict) -> None:
        self.tokens = tokens
        self.policy = policy
        self.levels: list[str] = policy["levels"]
        self.providers: dict[str, str] = policy["providers"]
        self._colors = {t["name"]: t["value"] for t in tokens["color"]["tokens"]}
        self.space = {t["name"]: t["value"] for t in tokens["spacing"]["tokens"]}
        self.radius = {t["name"]: t["value"] for t in tokens["radius"]["tokens"]}
        self.shadow = {t["name"]: t["value"] for t in tokens["shadow"]["tokens"]}
        self.families = tokens["type"]["families"]
        self.styles: dict[str, dict] = {}
        for group in tokens["type"]["groups"]:
            for style in group["styles"]:
                self.styles[style["name"]] = {"family": group["family"], **style}

    # tokens

    def color(self, name: str, theme: str = "light") -> str:
        """A colour token, following an alias such as {text-restricted}."""
        value = self._colors[name]
        if isinstance(value, str):
            alias = re.fullmatch(r"\{([a-z0-9-]+)\}", value)
            if not alias:
                return value
            return self.color(alias.group(1), theme)
        return value[theme]

    def color_names(self) -> list[str]:
        return [t["name"] for t in self.tokens["color"]["tokens"]]

    def rgb(self, name: str, theme: str = "light") -> tuple[int, int, int]:
        h = self.color(name, theme).lstrip("#")
        return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]

    def px(self, style: str, key: str = "fontSize") -> int:
        return int(str(self.styles[style][key]).removesuffix("px"))

    def font(self, style: str) -> str:
        """The first family of a type style, which is what an SVG or a font URL needs."""
        stack = self.families[self.styles[style]["family"]]
        return stack.split(",")[0].strip().strip('"')

    # policy

    def rank(self, level: str) -> int:
        return self.levels.index(level)

    def cleared(self, level: str) -> list[str]:
        """Providers cleared to read `level`, lowest clearance first, file order within a level."""
        order = list(self.providers)
        return sorted(
            (p for p, c in self.providers.items() if self.rank(c) >= self.rank(level)),
            key=lambda p: (self.rank(self.providers[p]), order.index(p)),
        )

    def at(self, level: str) -> list[str]:
        """Providers whose own clearance is exactly `level`."""
        return [p for p, c in self.providers.items() if c == level]

    def marking(self, level: str) -> str:
        """The marking line a document carries, as in design-system/guidelines/30-github-cover.md."""
        return f"`{level.upper()}` · cleared: {', '.join(self.cleared(level))}"

    def band_right(self, level: str) -> str:
        """The right hand side of a band: who is cleared to see this page."""
        return "CLEARED: " + ", ".join(p.upper() for p in self.cleared(level))

    def workspaces(self) -> list[tuple[str, str]]:
        """Every labelled folder in the repo, as (path relative to root, level)."""
        found = []
        for label in sorted(ROOT.glob("*/*/.confidentiality.json")):
            level = json.loads(label.read_text(encoding="utf-8")).get("level")
            if level in self.levels:
                found.append((label.parent.relative_to(ROOT).as_posix(), level))
        return found


def load() -> Brand:
    return Brand(
        json.loads(TOKENS_FILE.read_text(encoding="utf-8")),
        json.loads(POLICY_FILE.read_text(encoding="utf-8")),
    )


