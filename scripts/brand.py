#!/usr/bin/env python3
"""Generate every marked surface from the two files that own the facts.

`design-system/tokens.json` owns the look. `.pi/confidentiality.json` owns the levels
and the clearances. Nothing else in this repo may type a hex value or a provider list
by hand.

The design system says the artifact is marked by the system it describes, and that the
band is "read from .pi/confidentiality.json rather than typed". Until this script
existed it was typed, in six places, and the GitHub banner had already drifted: it
still listed five providers and a ladder reading "4 of 5" after `verda` was added.

    python3 scripts/brand.py            # write every generated surface
    python3 scripts/brand.py --check    # exit 1 if a surface is out of date
    python3 scripts/brand.py --list     # what this script owns

Standard library only, like the audit skills. Flattening the two cover SVGs to
outlines needs inkscape (see design-system/components/CoverBanner/README.md); without
it those two files are skipped, everything else still runs, and --check says so.
"""

