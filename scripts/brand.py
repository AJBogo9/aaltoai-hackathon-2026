def tokens_css(b: Brand) -> str:
    def block(theme: str, indent: str) -> list[str]:
        return [f"{indent}--{name}: {b.color(name, theme)};" for name in b.color_names()]

    out = [f"/* {STAMP} */", "", ":root {"]
    out += block("light", "  ")
    out.append("")
    for key, stack in b.families.items():
        out.append(f"  --font-{key}: {stack};")
    out.append("")
    for name, value in b.space.items():
        out.append(f"  --{name}: {value};")
    for name, value in b.radius.items():
        out.append(f"  --{name}: {value};")
    for name, value in b.shadow.items():
        out.append(f"  --{name}: {value};")
    out += ["}", "", "/* Screen. The band fills stay dark in both themes, because band-ink is white in both. */"]
    out.append("@media (prefers-color-scheme: dark) {")
    out.append('  :root:not([data-theme="light"]) {')
    out += block("dark", "    ")
    out += ["  }", "}", "", ':root[data-theme="dark"] {']
    out += block("dark", "  ")
    out.append("}")
    return "\n".join(out) + "\n"


def tokens_py(b: Brand) -> str:
    """Constants for the Python surfaces: the report writer, the notebook, any future deck build."""
    levels = json.dumps(b.levels)
    providers = json.dumps(b.providers, indent=4)
    colors = {name: {t: b.color(name, t) for t in ("light", "dark")} for name in b.color_names()}
    ansi = {level: b.rgb(f"text-{level}", "dark") if f"text-{level}" in b._colors else b.rgb("text-confidential", "dark") for level in b.levels}
    out = [
        '"""' + STAMP + '"""',
        "",
        f"LEVELS = {levels}",
        f"PROVIDERS = {providers}",
        "",
        "COLOR = " + json.dumps(colors, indent=4),
        "",
        "SPACE = " + json.dumps(b.space, indent=4),
        "",
        "#: Providers cleared to read each level, lowest clearance first.",
        "CLEARED = " + json.dumps({level: b.cleared(level) for level in b.levels}, indent=4),
        "",
        "#: The marking line a generated document carries.",
        "MARKING = " + json.dumps({level: b.marking(level) for level in b.levels}, indent=4),
        "",
        "#: Terminal truecolor for a level, from the dark theme text tokens.",
        "LEVEL_RGB = " + json.dumps({k: list(v) for k, v in ansi.items()}, indent=4),
        "",
        "",
        "def marking(level: str) -> str:",
        '    """The marking line for a level, or a refusal to mark a level the policy does not know."""',
        "    if level not in MARKING:",
        '        raise ValueError(f"{level!r} is not a level in .pi/confidentiality.json: {LEVELS}")',
        "    return MARKING[level]",
        "",
    ]
    return "\n".join(out)


def brand_ts(b: Brand) -> str:
    """The terminal palette, so the product prints the colours the deck quotes."""
    low, high = b.levels[0], b.levels[-1]
    rgb = {
        "allow": b.rgb("signal-allow", "dark"),
        "between": b.rgb("text-confidential", "dark"),
        "refuse": b.rgb("signal-refuse", "dark"),
    }
    lines = [
        f"// {STAMP}",
        "//",
        "// The three level colours, from the dark theme text tokens, because a terminal is dark.",
        f"// allow is the lowest level ({low}), refuse is the highest ({high}) and the glyph colours",
        "// signal-allow and signal-refuse are aliases of those two, which is why a refusal is never",
        "// a fourth red. between carries every level in the middle.",
        "",
        "export type Paint = \"allow\" | \"between\" | \"refuse\" | \"dim\";",
        "",
        "export const RGB: Record<Exclude<Paint, \"dim\">, [number, number, number]> = {",
    ]
    for name, value in rgb.items():
        lines.append(f"  {name}: [{value[0]}, {value[1]}, {value[2]}],")
    lines += [
        "};",
        "",
        "/** The 4 bit fallback, for a terminal that does not report truecolor. */",
        "export const BASIC: Record<Exclude<Paint, \"dim\">, string> = {",
        '  allow: "\\x1b[32m",',
        '  between: "\\x1b[94m",',
        '  refuse: "\\x1b[31m",',
        "};",
        "",
    ]
    return "\n".join(lines)


def tokens_sh(b: Brand) -> str:
    """The band, for the launcher. The first frame of a live demo is a terminal."""
    lines = [
        f"# {STAMP}",
        "#",
        "# Band fills for a terminal, from the dark theme band tokens, because a terminal is",
        "# dark. BAND_RGB_<level> is 24 bit; BAND_BG_<level> is the 4 bit fallback, on the same",
        "# ordinal rule the status line uses: lowest green, highest red, everything between blue.",
        "",
    ]
    for i, level in enumerate(b.levels):
        basic = "42" if i == 0 else "41" if i == len(b.levels) - 1 else "44"
        lines.append(f'BAND_RGB_{level}="{";".join(str(c) for c in b.rgb(f"band-{level}", "dark"))}"')
        lines.append(f'BAND_BG_{level}="{basic}"')
    lines += [
        "",
        f'BAND_INK="{";".join(str(c) for c in b.rgb("band-ink", "dark"))}"',
        "",
        "# Providers cleared to read each level, lowest clearance first.",
    ]
    for level in b.levels:
        lines.append(f'CLEARED_{level}="{",".join(b.cleared(level))}"')
    return "\n".join(lines) + "\n"


