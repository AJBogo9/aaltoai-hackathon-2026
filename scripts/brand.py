def cover_svg(b: Brand, theme: str, level: str = "public", top: int = 0, height: int = 300) -> str:
    """The repository banner, with real text. flatten() turns it into outlines.

    The banner is 1280x300. A taller canvas (a negative `top`) is the same composition on
    more paper, for the social card, with the band still on the top edge of the image.
    """
    gutter = int(str(b.space["space-5"]).removesuffix("px"))
    right = 1280 - gutter
    band_h = 44
    band_size = b.px("cover-banner")
    tracking = round(band_size * 0.16, 2)

    # The band must not collide with itself. PT Mono advances 0.6em, plus the tracking.
    left_text, right_text = level.upper(), b.band_right(level)
    def band_width(text: str, size: float) -> float:
        return len(text) * (size * 0.6 + size * 0.16)
    size = band_size
    while size > 13 and band_width(left_text, size) + band_width(right_text, size) > (1280 - 2 * gutter - 24):
        size -= 0.5
    tracking = round(size * 0.16, 2)

    ladder = list(reversed(b.levels))  # highest at the top
    total = len(b.providers)
    unit = (right - 840) / max(total, 1)
    rows = []
    for i, lvl in enumerate(ladder):
        y = 103 + i * 52
        count = len(b.cleared(lvl))
        rows.append(
            f'  <rect x="840" y="{y}" width="{round(count * unit, 1)}" height="34" fill="{b.color(f"band-{lvl}", theme)}"/>\n'
            f'  <text x="853" y="{y + 23}" style="font-size:18px;font-family:\'{b.font("value")}\';'
            f'fill:{b.color("band-ink", theme)}">{lvl}</text>\n'
            f'  <text x="822" y="{y + 23}" style="font-size:18px;font-family:\'{b.font("value")}\';'
            f'text-anchor:end;fill:{b.color("ink-600", theme)}">{count} of {total}</text>'
        )

    alt = (
        "confidentiality-broker: access control for LLM agents. The folder carries a label, "
        "the provider carries a clearance, and the broker compares them on every tool call."
    )
    return (
        f'<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n'
        f"<!-- {STAMP} -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="{height}"'
        f' viewBox="0 {top} 1280 {height}" role="img" aria-labelledby="t" version="1.1">\n'
        f"  <title id=\"t\">{alt}</title>\n"
        f'  <rect x="0" y="{top}" width="1280" height="{height}" fill="{b.color("paper-000", theme)}"/>\n'
        f'  <rect x="0" y="{top}" width="1280" height="{band_h}" fill="{b.color(f"band-{level}", theme)}"/>\n'
        f'  <text x="{gutter}" y="{top + 29}" style="font-size:{size}px;font-family:\'{b.font("cover-banner")}\';'
        f'letter-spacing:{tracking};fill:{b.color("band-ink", theme)}">{left_text}</text>\n'
        f'  <text x="{right}" y="{top + 29}" style="font-size:{size}px;font-family:\'{b.font("cover-banner")}\';'
        f'letter-spacing:{tracking};text-anchor:end;fill:{b.color("band-ink", theme)}">{right_text}</text>\n'
        f'  <text x="{gutter}" y="158" style="font-size:{b.px("cover-name")}px;'
        f'font-family:\'{b.font("cover-name")}\';fill:{b.color("ink-900", theme)}">confidentiality-broker</text>\n'
        f'  <text x="{gutter}" y="211" style="font-size:30px;font-family:\'{b.font("cover-tag")}\';'
        f'fill:{b.color("ink-600", theme)}">A label on the folder. A clearance on the provider.</text>\n'
        f'  <text x="{gutter}" y="248" style="font-size:19px;font-family:\'{b.font("value")}\';'
        f'fill:{b.color("ink-400", theme)}">compared on every tool call, in code, never in the prompt</text>\n'
        f'  <text x="840" y="88" style="font-size:14px;font-family:\'{b.font("label")}\';letter-spacing:2;'
        f'fill:{b.color("ink-400", theme)}">PROVIDERS CLEARED TO READ IT</text>\n' + "\n".join(rows) + "\n</svg>\n"
    )


def inkscape() -> str | None:
    return shutil.which("inkscape")


def _clean_env() -> dict:
    """Snap provided library paths break the system inkscape. Drop them for the child only."""
    env = dict(os.environ)
    for key in ("LD_LIBRARY_PATH", "GTK_PATH", "GIO_MODULE_DIR", "LOCPATH", "GDK_PIXBUF_MODULE_FILE"):
        env.pop(key, None)
    return env


def flatten(svg: str, out: Path) -> None:
    """Author with real text, then flatten: an SVG in an <img> cannot load a font."""
    binary = inkscape()
    if binary is None:
        raise RuntimeError("inkscape is not installed, so the cover text cannot be flattened to outlines")
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "raw.svg"
        raw.write_text(svg, encoding="utf-8")
        subprocess.run(
            [binary, str(raw), "--export-type=svg", "--export-text-to-path", "--export-plain-svg",
             f"--export-filename={out}"],
            check=True, env=_clean_env(), stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
    text = out.read_text(encoding="utf-8")
    if "<text" in text:
        raise RuntimeError(f"{out} still has a <text> element, so a reader without PT Mono sees a fallback face")
    if not text.lstrip().startswith("<?xml"):
        text = '<?xml version="1.0" encoding="UTF-8" standalone="no"?>' + text
    out.write_text(text.replace("<svg", f"<!-- {STAMP} --><svg", 1), encoding="utf-8")


def social_png(b: Brand, out: Path) -> None:
    """1200x630 for og:image. A link to the deck should arrive marked."""
    binary = inkscape()
    if binary is None:
        raise RuntimeError("inkscape is not installed, so the social card cannot be rendered")
    # The same composition on a 1280x630 canvas: band on the top edge, content where it
    # sits on the banner, paper everywhere else. Exported at 1200 wide, which is the size
    # every link unfurler wants.
    card = cover_svg(b, "light", top=-165, height=630)
    with tempfile.TemporaryDirectory() as tmp:
        raw = Path(tmp) / "card.svg"
        raw.write_text(card, encoding="utf-8")
        subprocess.run(
            [binary, str(raw), "--export-type=png", "--export-width=1200", f"--export-filename={out}"],
            check=True, env=_clean_env(), stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )


# ------------------------------------------------------- blocks inside handwritten files


def block(marker: str, body: str, comment: str = "html") -> tuple[str, str, str]:
    open_, close = {
        "html": (f"<!-- brand:{marker} -->", f"<!-- /brand:{marker} -->"),
        "css": (f"/* brand:{marker} */", f"/* /brand:{marker} */"),
    }[comment]
    return open_, close, body


def replace_block(text: str, open_: str, close: str, body: str) -> str:
    pattern = re.compile(re.escape(open_) + r".*?" + re.escape(close), re.S)
    if not pattern.search(text):
        raise RuntimeError(f"no {open_} block to fill")
    return pattern.sub(lambda _: f"{open_}\n{body}\n{close}", text, count=1)


def test_count() -> int:
    """The badge states a number, so the number is counted rather than remembered.

    node:test registers one test per top level test() call and the suite has no dynamic
    ones, so this is the figure `npm test` prints.
    """
    tests = (ROOT / ".pi" / "extensions" / "confidentiality-broker").glob("*.test.ts")
    return sum(len(re.findall(r"^\s*test\(", f.read_text(encoding="utf-8"), re.M)) for f in tests)


