WORDS = ["no", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve"]


def spelled(n: int) -> str:
    """Prose counts are words. A number in prose reads as machine output, and this is prose."""
    return WORDS[n] if n < len(WORDS) else str(n)


def ds_marking_table(b: Brand) -> str:
    rows = [
        ("Nothing confidential (a mechanism diagram, the roadmap, the title)", "public"),
        ("A confidential path, filename or field name", "confidential"),
        ("Anything from the health workspace", "restricted"),
    ]
    out = ["| The page shows | Band | Fill token |", "| --- | --- | --- |"]
    for shows, level in rows:
        if level not in b.levels:
            continue
        n = len(b.cleared(level))
        out.append(f"| {shows} | `{level.upper()}` and the {spelled(n)} cleared providers | `band-{level}` |")
    return "\n".join(out)


def demo_workspace_table(b: Brand) -> str:
    out = ["| Workspace | Label | Providers cleared |", "|---|---|---|"]
    for path, level in b.workspaces():
        out.append(f"| `{path}` | `{level}` | {', '.join(b.cleared(level))} |")
    return "\n".join(out)


